package com.revetsec.totp;

import java.util.HashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import org.jspecify.annotations.NonNull;

/**
 * An atomic comparison of every observed version and absence followed by all mutations or none.
 * The backend must atomically compare its active recovery epoch too. Versions are generated by
 * core, authenticated in the envelope, preserved exactly and never reused. There is no deletion,
 * expiry or eviction operation: permanent fences survive credential removal.
 * @since 1.0.0
 */
@javax.annotation.concurrent.Immutable
public final class TotpStoreWrite {
 private final TotpStoreWrite.@NonNull Purpose purpose;
 private final @NonNull TotpStoreSnapshot snapshot;
 private final @NonNull List<TotpStoreWrite.@NonNull Mutation> mutations;
 private final @NonNull String credentialNamespace;
 private final @NonNull String recoveryEpoch;
 private TotpStoreWrite(TotpStoreWrite.@NonNull Purpose purpose, @NonNull TotpStoreSnapshot snapshot,
   @NonNull List<TotpStoreWrite.@NonNull Mutation> mutations) {
  this.purpose = purpose; this.snapshot = snapshot; this.mutations = List.copyOf(mutations);
  TotpStoreKey first = snapshot.getEntries().keySet().iterator().next();
  this.credentialNamespace = first.getCredentialNamespace(); this.recoveryEpoch = first.getRecoveryEpoch();
 }
 /**
  * Combines a complete predicate set with at most 16 distinct insertions or replacements.
  * Initialization contains exactly the absent namespace record and its insertion. Updates must
  * include a present namespace record predicate. An empty mutation set remains a predicate barrier.
  * @param purpose namespace initialization or ordinary update
  * @param snapshot the complete read set
  * @param mutations the bounded change set
  * @return the validated write
  * @since 1.0.0
  */
 public static @NonNull TotpStoreWrite fromSnapshotAndMutations(TotpStoreWrite.@NonNull Purpose purpose,
   @NonNull TotpStoreSnapshot snapshot, @NonNull List<TotpStoreWrite.@NonNull Mutation> mutations) {
  Objects.requireNonNull(purpose); Objects.requireNonNull(snapshot); Objects.requireNonNull(mutations);
  if (mutations.size() > 16) throw new IllegalArgumentException("Too many TOTP mutations");
  TotpStoreKey first = snapshot.getEntries().keySet().iterator().next();
  TotpStoreKey namespace = TotpStoreKey.forNamespace(first.getCredentialNamespace(), first.getRecoveryEpoch());
  TotpStoreEntry namespaceEntry = snapshot.getEntries().get(namespace);
  if (purpose == Purpose.INITIALIZE_NAMESPACE) {
   if (snapshot.getEntries().size() != 1 || !(namespaceEntry instanceof TotpStoreEntry.Absent)
     || mutations.size() != 1 || !mutations.get(0).getKey().equals(namespace)
     || mutations.get(0).kind != Mutation.Kind.INSERT)
    throw new IllegalArgumentException("Invalid TOTP namespace initialization");
  } else if (!(namespaceEntry instanceof TotpStoreEntry.Present))
   throw new IllegalArgumentException("TOTP update requires a present namespace predicate");
  Set<TotpStoreKey> changed = new HashSet<>();
  for (Mutation mutation : mutations) {
   TotpStoreEntry prior = snapshot.getEntry(mutation.getKey());
   if (!changed.add(mutation.getKey())
     || (mutation.kind == Mutation.Kind.INSERT && !(prior instanceof TotpStoreEntry.Absent))
     || (mutation.kind == Mutation.Kind.REPLACE && !(prior instanceof TotpStoreEntry.Present))
     || (prior instanceof TotpStoreEntry.Present present
       && present.getRecord().getVersion().equals(mutation.record.getVersion())))
    throw new IllegalArgumentException("Invalid TOTP store mutation");
  }
  return new TotpStoreWrite(purpose, snapshot, mutations);
 }
 /**
  * Returns the authoritative namespace.
  * @return the namespace
  * @since 1.0.0
  */
 public @NonNull String getCredentialNamespace() { return this.credentialNamespace; }
 /**
  * Returns the recovery epoch that must be checked within the commit transaction.
  * @return the epoch
  * @since 1.0.0
  */
 public @NonNull String getRecoveryEpoch() { return this.recoveryEpoch; }
 /**
  * Returns initialization or update purpose.
  * @return the purpose
  * @since 1.0.0
  */
 public TotpStoreWrite.@NonNull Purpose getPurpose() { return this.purpose; }
 /**
  * Returns every exact version and absence predicate.
  * @return the snapshot
  * @since 1.0.0
  */
 public @NonNull TotpStoreSnapshot getSnapshot() { return this.snapshot; }
 /**
  * Returns the immutable mutation list.
  * @return the mutations
  * @since 1.0.0
  */
 public @NonNull List<TotpStoreWrite.@NonNull Mutation> getMutations() { return this.mutations; }
 /**
  * Redacts predicates and mutations.
  * @since 1.0.0
  */
 @Override public @NonNull String toString() { return "TotpStoreWrite{write=<redacted>}"; }
 /**
  * Distinguishes one-time initialization from updates that cannot recreate the namespace.
  * @since 1.0.0
  */
 @javax.annotation.concurrent.Immutable
 public enum Purpose {
  /**
   * Activate only a newly provisioned recovery epoch.
   * @since 1.0.0
   */ INITIALIZE_NAMESPACE,
  /**
   * Compare an existing initialized namespace fence.
   * @since 1.0.0
   */ UPDATE
 }
 /**
  * An insertion or replacement of one permanent record.
  * @since 1.0.0
  */
 @javax.annotation.concurrent.Immutable
 public static final class Mutation {
  private final Mutation.@NonNull Kind kind;
  private final @NonNull TotpStoreRecord record;
  private Mutation(Mutation.@NonNull Kind kind, @NonNull TotpStoreRecord record) {
   this.kind = kind; this.record = Objects.requireNonNull(record);
  }
  /**
   * Inserts only after a matching confirmed absence predicate.
   * @param record the new record
   * @return the insertion
   * @since 1.0.0
   */
  public static @NonNull Mutation insert(@NonNull TotpStoreRecord record) { return new Mutation(Kind.INSERT, record); }
  /**
   * Replaces only after a matching exact version predicate.
   * @param record the replacement with a fresh non-reused version
   * @return the replacement
   * @since 1.0.0
   */
  public static @NonNull Mutation replace(@NonNull TotpStoreRecord record) { return new Mutation(Kind.REPLACE, record); }
  /**
   * Returns the changed address.
   * @return the address
   * @since 1.0.0
   */
  public @NonNull TotpStoreKey getKey() { return this.record.getKey(); }
  /**
   * Returns the immutable replacement record.
   * @return the record
   * @since 1.0.0
   */
  public @NonNull TotpStoreRecord getRecord() { return this.record; }
  /**
   * Returns the mutation kind.
   * @return the kind
   * @since 1.0.0
   */
  public Mutation.@NonNull Kind getKind() { return this.kind; }
  /**
   * Redacts the record.
   * @since 1.0.0
   */
  @Override public @NonNull String toString() { return "Mutation{record=<redacted>}"; }
  /**
   * Permanent insertion or replacement; deletion is deliberately unavailable.
   * @since 1.0.0
   */
  @javax.annotation.concurrent.Immutable
  public enum Kind {
   /**
    * Insert after confirmed absence.
    * @since 1.0.0
    */ INSERT,
   /**
    * Replace an exact version.
    * @since 1.0.0
    */ REPLACE
  }
 }
}
